// Package audit предоставляет реализацию паттерна "Наблюдатель" для аудита событий.
// Позволяет регистрировать различные обработчики событий (наблюдателей),
// которые будут получать уведомления о происходящих событиях в системе.
package audit

import (
	"sync"

	"github.com/kirillshkro/gshortener/internal/types"
)

// Observer определяет интерфейс для наблюдателей, которые могут получать уведомления о событиях.
// Любая структура, реализующая этот интерфейс, может быть зарегистрирована как наблюдатель
// и будет получать события через метод Notify.
type Observer interface {
	// Notify обрабатывает полученное событие.
	// Реализация должна быть потокобезопасной, так как метод может вызываться
	// одновременно из разных горутин.
	//
	// Параметры:
	//   - e: указатель на событие, содержащее информацию о произошедшем действии
	//
	// Возвращает:
	//   - error: ошибка при обработке события
	Notify(e *types.Event) error

	// Close закрывает наблюдатель и освобождает ресурсы.
	// Должна быть вызвана при завершении работы приложения.
	//
	// Возвращает:
	//   - error: ошибка при закрытии
	Close() error
}

// Subject представляет собой субъект, за которым наблюдают.
// Реализует паттерн "Наблюдатель" (Observer) и управляет списком
// зарегистрированных наблюдателей, рассылая им уведомления о событиях.
//
// Потокобезопасен благодаря использованию RWMutex для защиты списка наблюдателей.
type Subject struct {
	observers []Observer   // Список зарегистрированных наблюдателей
	mu        sync.RWMutex // Мьютекс для синхронизации доступа к списку наблюдателей
}

// NewSubject создает новый экземпляр Subject с инициализированным списком наблюдателей.
//
// Возвращает:
//   - *Subject: указатель на новый экземпляр Subject
func NewSubject() *Subject {
	return &Subject{
		observers: make([]Observer, 0),
	}
}

// Register добавляет нового наблюдателя в список.
// Если наблюдатель уже зарегистрирован, он будет добавлен повторно,
// что может привести к дублированию уведомлений.
//
// Параметры:
//   - o: наблюдатель, который будет получать уведомления о событиях
//
// Метод потокобезопасен и может вызываться одновременно из разных горутин.
func (s *Subject) Register(o Observer) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.observers = append(s.observers, o)
}

// Remove удаляет наблюдателя из списка.
// Если наблюдатель не найден, метод ничего не делает.
// При наличии дубликатов удаляется только первое вхождение.
//
// Параметры:
//   - o: наблюдатель, который должен быть удален
//
// Метод потокобезопасен и может вызываться одновременно из разных горутин.
func (s *Subject) Remove(o Observer) {
	s.mu.Lock()
	defer s.mu.Unlock()
	for i, observer := range s.observers {
		if observer == o {
			// Удаляем элемент, сохраняя порядок остальных
			s.observers = append(s.observers[:i], s.observers[i+1:]...)
			return
		}
	}
}

// Notify рассылает уведомление о событии всем зарегистрированным наблюдателям.
// Каждое уведомление обрабатывается в отдельной горутине, что обеспечивает
// асинхронность и независимость обработки.
//
// Важно: метод не дожидается завершения обработки уведомлений наблюдателями.
// При необходимости синхронной обработки следует реализовать отдельный метод.
//
// Параметры:
//   - e: указатель на событие, которое будет передано всем наблюдателям
//
// Метод потокобезопасен и может вызываться одновременно из разных горутин.
// Для чтения списка наблюдателей используется RLock, что позволяет
// параллельно выполнять другие операции чтения.
func (s *Subject) Notify(e *types.Event) {
	s.mu.RLock()
	defer s.mu.RUnlock()

	// Запускаем каждого наблюдателя в отдельной горутине
	for _, observer := range s.observers {
		go observer.Notify(e)
	}
}
