// Package middleware предоставляет HTTP-промежуточные обработчики (middleware)
// для сжатия данных, логирования, аутентификации и других сквозных задач.
package middleware

import (
	"compress/gzip"
	"io"
)

// compReader реализует io.ReadCloser для распаковки gzip-сжатых данных.
// Оборачивает оригинальный ReadCloser тела запроса и обеспечивает
// прозрачную распаковку данных при чтении.
//
// Структура используется в middleware HandlerWithGzip для поддержки
// сжатых входящих запросов от клиентов.
//
// Важно: всегда вызывайте Close() после завершения работы с данным
// для корректного освобождения ресурсов и завершения gzip-ридера.
type compReader struct {
	r  io.ReadCloser // Оригинальный ReadCloser тела запроса
	zr io.ReadCloser // Gzip-ридер для распаковки данных
}

// newCompReader создает новый экземпляр compReader для распаковки gzip-данных.
// Выполняет инициализацию gzip-ридера на основе переданного ReadCloser.
//
// Процесс создания:
// 1. Создает gzip-ридер из оригинального ReadCloser
// 2. При ошибке возвращает её вызывающему коду
// 3. Возвращает структуру compReader, объединяющую оба ридера
//
// Параметры:
//   - r: оригинальный ReadCloser (обычно тело HTTP-запроса)
//
// Возвращает:
//   - *compReader: указатель на созданный экземпляр compReader
//   - error: ошибка при создании gzip-ридера (например, поврежденные данные)
func newCompReader(r io.ReadCloser) (*compReader, error) {
	zr, err := gzip.NewReader(r)
	if err != nil {
		return nil, err
	}

	return &compReader{
		r:  r,
		zr: zr,
	}, nil
}

// Close закрывает gzip-ридер и освобождает связанные ресурсы.
// Важно: при использовании compReader необходимо вызывать Close()
// в блоке defer для гарантированного освобождения ресурсов.
//
// Закрытие выполняется в два этапа:
// 1. Закрывается gzip-ридер (завершает распаковку и освобождает буферы)
// 2. Оригинальный ReadCloser закрывается автоматически через gzip-ридер
//
// Возвращает:
//   - error: ошибка при закрытии gzip-ридера (если возникла)
func (c *compReader) Close() error {
	// Закрываем gzip-ридер, который также закроет оригинальный r
	return c.zr.Close()
}

// Read читает распакованные данные из тела запроса.
// Прозрачно выполняет распаковку gzip-сжатых данных.
//
// Метод реализует интерфейс io.Reader и может использоваться
// в любом месте, где требуется чтение данных.
//
// Особенности чтения:
//   - Данные распаковываются "на лету" по мере чтения
//   - Не требует загрузки всего тела в память
//   - Поддерживает потоковую обработку больших данных
//
// Параметры:
//   - b: буфер для записи прочитанных данных
//
// Возвращает:
//   - n: количество прочитанных байт
//   - err: ошибка чтения (io.EOF при достижении конца данных)
func (c compReader) Read(b []byte) (n int, err error) {
	return c.zr.Read(b)
}
